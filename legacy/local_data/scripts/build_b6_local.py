from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

from memoryflow.b6_split import (
    GROUP_SEED,
    ORDER_SEEDS,
    build_eligible_pool,
    deduplicate_partition_pools,
    discover_run_roles,
    materialize_rows,
    sample_partition,
    slot_distribution,
    split_exposed_runs,
    validate_cross_splits,
    write_bundle,
)


def load_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def human_size(size: int) -> str:
    value = float(size)
    for unit in ("B", "KiB", "MiB", "GiB"):
        if value < 1024 or unit == "GiB":
            return f"{value:.2f} {unit}"
        value /= 1024
    raise AssertionError("unreachable")


def class_counts(rows: list[dict]) -> tuple[int, int]:
    single = sum(len(row["gold_source_ids"]) == 1 for row in rows)
    return single, len(rows) - single


def capped_class_capacity(rows: list[dict], per_run_cap: int) -> dict[str, int]:
    counts: dict[str, Counter] = defaultdict(Counter)
    for row in rows:
        label = "single" if len(row["gold_source_ids"]) == 1 else "multi"
        counts[row["run_id"]][label] += 1
    return {
        label: sum(min(per_run_cap, values[label]) for values in counts.values())
        for label in ("single", "multi")
    }


def slot_table(rows: list[dict]) -> str:
    lines = ["| Position | Candidates | Gold appearances | Single-positive gold |", "|---:|---:|---:|---:|"]
    lines.extend(
        f"| {item['slot']} | {item['candidate_count']} | {item['gold_count']} | {item['single_positive_gold_count']} |"
        for item in slot_distribution(rows)
    )
    return "\n".join(lines)


def overlap_table(validation: dict) -> str:
    lines = ["| Pair | run | example | target hash | target+candidate fingerprint | candidate-ID set |", "|---|---:|---:|---:|---:|---:|"]
    for pair, counts in sorted(validation["cross_split_overlaps"].items()):
        lines.append(
            f"| `{pair}` | {counts['run_id']} | {counts['example_id']} | {counts['target_hash']} | "
            f"{counts['target_candidate_hash']} | {counts['candidate_set_hash']} |"
        )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--replace-generated", action="store_true", help="refresh only files generated by this B6 script")
    args = parser.parse_args()
    root = args.root.resolve()
    outputs = {
        "train": root / "remote_bundle" / "checkpoint_b6_train",
        "validation": root / "remote_bundle" / "checkpoint_b6_validation",
        "final_test": root / "sealed" / "checkpoint_b6_final_test",
    }
    report_path = root / "checkpoint_b6_local_split_report.md"
    if (report_path.exists() or any(path.exists() for path in outputs.values())) and not args.replace_generated:
        raise FileExistsError("refusing to overwrite an existing B6 output")

    processed = root / "data" / "processed"
    examples = load_jsonl(processed / "citation_examples.jsonl")
    candidate_rows = load_jsonl(processed / "candidate_sets.jsonl")
    sources = load_jsonl(processed / "sources.jsonl")
    debug_rows = load_jsonl(root / "remote_bundle" / "checkpoint_b_debug" / "data" / "debug_examples.jsonl")
    b4_rows = load_jsonl(root / "remote_bundle" / "checkpoint_b4_holdout" / "examples.jsonl")

    exposed_runs, unseen_runs = discover_run_roles(examples, debug_rows, b4_rows)
    train_runs, validation_runs = split_exposed_runs(exposed_runs)
    if train_runs & validation_runs or (train_runs | validation_runs) != exposed_runs:
        raise RuntimeError("exposed run partition failed")
    if unseen_runs & exposed_runs:
        raise RuntimeError("unseen runs overlap exposed runs")

    raw_pools = {
        "train": build_eligible_pool(examples, candidate_rows, sources, train_runs),
        "validation": build_eligible_pool(examples, candidate_rows, sources, validation_runs),
        "final_test": build_eligible_pool(examples, candidate_rows, sources, unseen_runs),
    }
    pools, dedup_report = deduplicate_partition_pools(raw_pools)
    sample_specs = {
        "train": (2000, 2000, 40),
        "validation": (400, 400, 40),
        "final_test": (300, 300, 20),
    }
    selected = {
        split: sample_partition(
            pools[split], target_single=spec[0], target_multi=spec[1], per_run_cap=spec[2], seed=f"{GROUP_SEED}:{split}:sample"
        )
        for split, spec in sample_specs.items()
    }
    capacities = {
        split: capped_class_capacity(pools[split], spec[2])
        for split, spec in sample_specs.items()
    }
    materialized = {
        split: materialize_rows(rows, sources, split, ORDER_SEEDS[split])
        for split, rows in selected.items()
    }
    validation = validate_cross_splits(materialized)
    if not validation["passed"]:
        raise RuntimeError(f"cross-split validation failed: {json.dumps(validation, ensure_ascii=False)}")

    expected_runs = {"train": train_runs, "validation": validation_runs, "final_test": unseen_runs}
    for split, rows in materialized.items():
        if not {row["run_id"] for row in rows} <= expected_runs[split]:
            raise RuntimeError(f"{split} contains a run outside its assigned partition")
        cap = sample_specs[split][2]
        run_counts = {run_id: sum(row["run_id"] == run_id for row in rows) for run_id in {row["run_id"] for row in rows}}
        if max(run_counts.values(), default=0) > cap:
            raise RuntimeError(f"{split} exceeds per-run cap")

    bundle_results = {
        split: write_bundle(
            outputs[split],
            materialized[split],
            seed=ORDER_SEEDS[split],
            group_seed=GROUP_SEED,
            sealed=split == "final_test",
            replace_generated=args.replace_generated,
        )
        for split in ("train", "validation", "final_test")
    }
    if not all(result["checksums_valid"] for result in bundle_results.values()):
        raise RuntimeError("bundle checksum verification failed")

    train_single, train_multi = class_counts(materialized["train"])
    validation_single, validation_multi = class_counts(materialized["validation"])
    final_single, final_multi = class_counts(materialized["final_test"])
    report = f"""# MemoryFlow Checkpoint B6-Local run-level split report

## Data roles and run split

- Stable parent grouping field: `run_id`. Neither checkpoint B debug nor B4 exposes `request_id`, `thread_id`, or another parent grouping field.
- Group split seed: `{GROUP_SEED}`
- Exposed runs: **{len(exposed_runs)}**
- Unseen runs: **{len(unseen_runs)}**
- Train run partition: **{len(train_runs)}** ({len(train_runs) / len(exposed_runs):.2%} of exposed runs)
- Validation run partition: **{len(validation_runs)}** ({len(validation_runs) / len(exposed_runs):.2%} of exposed runs)
- Final-test partition: all **{len(unseen_runs)}** unseen runs; none were used for training or validation.

The run partition was fixed before example sampling. Selection used only labels and structural validity; it did not use text quality, topic, length, lexical overlap, model scores, or expected difficulty.

## Actual datasets

| Dataset | Examples | Single | Multi | Independent runs | Per-run cap |
|---|---:|---:|---:|---:|---:|
| Train | {len(materialized['train'])} | {train_single} | {train_multi} | {len({row['run_id'] for row in materialized['train']})} | 40 |
| Validation | {len(materialized['validation'])} | {validation_single} | {validation_multi} | {len({row['run_id'] for row in materialized['validation']})} | 40 |
| Final test sealed | {len(materialized['final_test'])} | {final_single} | {final_multi} | {len({row['run_id'] for row in materialized['final_test']})} | 20 |

Class capacity after structural filtering, priority deduplication, and the per-run cap was: train single={capacities['train']['single']}, multi={capacities['train']['multi']}; validation single={capacities['validation']['single']}, multi={capacities['validation']['multi']}; final-test single={capacities['final_test']['single']}, multi={capacities['final_test']['multi']}. Train multi-positive capacity was below 2000, so every cap-compatible multi-positive was used and single-positive rows filled the remaining total, as required. Other requested class targets were attainable.

## Cross-dataset isolation

{overlap_table(validation)}

- Every row has exactly four unique candidate IDs: `{str(all(item['exact_four_candidates'] == item['example_count'] and item['candidate_ids_unique'] for item in validation['splits'].values())).lower()}`
- Gold resolution rate: **100%** in all three datasets.
- Candidate Source text is nonempty: `{str(all(item['source_text_nonempty'] for item in validation['splits'].values())).lower()}`
- Priority deduplication order: final test > validation > train.
- Removed from validation due to higher-priority duplication: **{sum(dedup_report['validation'].values())}**.
- Removed from train due to higher-priority duplication: **{sum(dedup_report['train'].values())}**.

## Train candidate-position distribution

{slot_table(materialized['train'])}

## Validation candidate-position distribution

{slot_table(materialized['validation'])}

## Sealed final test

The local sealed package contains **{len(materialized['final_test'])} examples across {len({row['run_id'] for row in materialized['final_test']})} unseen runs**. Candidate-position details are intentionally withheld. It was not copied to `remote_bundle`, was not uploaded, and must not be evaluated or uploaded until the B6 method and all training configuration are frozen.

## Bundles

| Role | Directory | Size | Bundle checksum (`SHA256(checksums.sha256)`) | Upload now? |
|---|---|---:|---|---|
| Train | `{outputs['train']}` | {human_size(bundle_results['train']['size_bytes'])} | `{bundle_results['train']['bundle_checksum']}` | Yes |
| Validation | `{outputs['validation']}` | {human_size(bundle_results['validation']['size_bytes'])} | `{bundle_results['validation']['bundle_checksum']}` | Yes |
| Final test sealed | `{outputs['final_test']}` | {human_size(bundle_results['final_test']['size_bytes'])} | `{bundle_results['final_test']['bundle_checksum']}` | **No — do not upload** |

Upload only these directories now:

- `{outputs['train']}`
- `{outputs['validation']}`

No model, GPU, Attention/QK score, server result, or raw log was read or used.
"""
    report_path.write_text(report, encoding="utf-8", newline="\n")
    print(json.dumps({
        "exposed_runs": len(exposed_runs),
        "unseen_runs": len(unseen_runs),
        "train": {"examples": len(materialized["train"]), "single": train_single, "multi": train_multi, "runs": len({row["run_id"] for row in materialized["train"]}), **bundle_results["train"]},
        "validation": {"examples": len(materialized["validation"]), "single": validation_single, "multi": validation_multi, "runs": len({row["run_id"] for row in materialized["validation"]}), **bundle_results["validation"]},
        "final_test": {"examples": len(materialized["final_test"]), "runs": len({row["run_id"] for row in materialized["final_test"]}), "size_bytes": bundle_results["final_test"]["size_bytes"], "bundle_checksum": bundle_results["final_test"]["bundle_checksum"]},
        "validation_passed": validation["passed"],
        "report": str(report_path),
    }, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
